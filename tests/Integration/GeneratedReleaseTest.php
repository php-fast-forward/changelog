/** Real disposable Git objects with simulated HTTP and Bot signature metadata; no remote writes. */
#[CoversNothing]
final class GeneratedReleaseTest extends TestCase
{
    /** One native transaction binds generated bytes; repeat, ownership and publication remain exact. */
    public function testNativeGeneratedReleaseTransaction(): void
    {
        $root = realpath(sys_get_temp_dir()) . '/generated-release-proof-' . bin2hex(random_bytes(8));
        mkdir($root, 0700);
        try {
            $git = static function (
                array $args,
                ?string $input = null,
                array $environment = [],
                bool $allowFailure = false,
            ) use (
                $root
            ): ?string {
                $process = new Process([
                    'git',
                    '-C',
                    $root,
                    ...$args,
                ], env: ['GIT_CONFIG_GLOBAL' => '/dev/null', 'GIT_CONFIG_SYSTEM' => '/dev/null', ...$environment], timeout: 30);
                $process->setInput($input);
                $process->run();
                if (!$process->isSuccessful()) {
                    if ($allowFailure) {
                        return null;
                    }

                    throw new RuntimeException('Fixture Git failed: ' . $process->getErrorOutput());
                }

                return $process->getOutput();
            };
            $commit = static function (string $message) use ($git): void {
                $git([
                    '-c',
                    'user.name=Fixture',
                    '-c',
                    'user.email=fixture@example.invalid',
                    '-c',
                    'commit.gpgsign=false',
                    '-c',
                    'core.hooksPath=/dev/null',
                    'commit',
                    '-qm',
                    $message,
                ]);
            };
            $git(['init','-q','-b','main']);
            mkdir($root . '/dist');
            file_put_contents($root . '/dist/tool', "old\0binary");
            chmod($root . '/dist/tool', 0755);
            file_put_contents(
                $root . '/CHANGELOG.md',
                "# Changelog\n\n## [0.1.0] - 2026-11-01\n\n### Added\n\n- Initial release.\n",
            );
            $git(['add','.']);
            $commit('initial');
            $git(['tag','v0.1.0']);
            mkdir($root . '/.changelog');
            file_put_contents(
                $root . '/.changelog/feature.md',
                "---\ncategory: fixed\ntype: patch\n---\n\nFix the fixture.\n",
            );
            $git(['add','.']);
            $commit('contribution');
            $base = trim($git(['rev-parse','HEAD']));
            $newBytes = "new\0binary\xff";
            file_put_contents($root . '/dist/tool', $newBytes);
            $state = ['head' => null, 'pr' => null, 'writes' => [], 'manual' => false];
            $actor = ['login' => 'github-actions[bot]', 'type' => 'Bot', 'id' => 101];
            $repo = ['id' => 1, 'node_id' => 'R_fixture', 'full_name' => 'fixture/repo'];
            $entries = static function (string $sha) use ($git): array {
                $out = [];
                foreach (explode("\0", rtrim($git(['ls-tree','-l','-z',$sha]), "\0")) as $record) {
                    if ($record === '') {
                        continue;
                    }
                    if (!preg_match(
                        '/^(\d+) (\w+) ([a-f0-9]+)\s+(-|\d+)\t(.+)$/sD',
                        $record,
                        $m,
                    )) {
                        throw new RuntimeException(
                            'Bad tree fixture',
                        );
                    }
                    $out[] = ['mode' => $m[1],'type' => $m[2],'sha' => $m[3],'size' => $m[4] === '-' ? null : (int) $m[4],'path' => $m[5]];
                }

                return $out;
            };
            $http = new MockHttpClient(static function (string $method, string $url, array $options) use (
                &$state,
                $base,
                $repo,
                $actor,
                $root,
                $git,
                $entries
            ): MockResponse {
                $path = parse_url($url, PHP_URL_PATH);
                parse_str(parse_url($url, PHP_URL_QUERY) ?? '', $query);
                $body = null;
                if ($method !== 'GET') {
                    if (is_callable($options['body'])) {
                        $encoded = '';
                        while (($chunk = $options['body']()) !== '') {
                            $encoded .= $chunk;
                        }
                    } else {
                        $encoded = $options['body'];
                    }
                    $body = json_decode($encoded, true, flags: JSON_THROW_ON_ERROR);
                    $state['writes'][] = [$method,$path];
                }
                $answer = null;
                $status = 200;
                if (str_starts_with($path, '/users/')) {
                    $answer = $actor;
                } elseif (str_contains(
                    $path,
                    '/git/ref/heads/main',
                )) {
                    $answer = ['object' => ['type' => 'commit','sha' => $base]];
                } elseif (str_contains(
                    $path,
                    '/git/ref/heads/changelog',
                )) {
                    $answer = $state['head'] === null ? null : ['object' => ['type' => 'commit','sha' => $state['head']]];
                } elseif ($method === 'POST' && str_ends_with(
                    $path,
                    '/git/blobs',
                )) {
                    $raw = base64_decode(
                        $body['content'],
                        true,
                    );
                    $sha = trim(
                        $git(['hash-object','-w','--stdin'], $raw),
                    );
                    $answer = ['sha' => $sha];
                    $status = 201;
                } elseif ($method === 'GET' && preg_match(
                    '~/git/blobs/([a-f0-9]{40})$~',
                    $path,
                    $m,
                )) {
                    return new MockResponse($git([
                        'cat-file',
                        'blob',
                        $m[1],
                    ]), ['http_code' => 200]);
                } elseif ($method === 'POST' && str_ends_with(
                    $path,
                    '/git/trees',
                )) {
                    $env = ['GIT_INDEX_FILE' => $root . '/generated.index'];
                    $git([
                        'read-tree',
                        $body['base_tree'],
                    ], environment: $env);
                    foreach ($body['tree'] as $entry) {
                        if (array_key_exists('sha', $entry) && $entry['sha'] === null) {
                            $git([
                                'update-index',
                                '--force-remove',
                                '--',
                                $entry['path'],
                            ], environment: $env);

                            continue;
                        }
                        $sha = $entry['sha'] ?? trim($git(['hash-object','-w','--stdin'], $entry['content']));
                        $git([
                            'update-index',
                            '--add',
                            '--cacheinfo',
                            $entry['mode'] . ',' . $sha . ',' . $entry['path'],
                        ], environment: $env);
                    }
                    $answer = ['sha' => trim($git(['write-tree'], environment: $env))];
                    $status = 201;
                } elseif ($method === 'POST' && str_ends_with($path, '/git/commits')) {
                    $args = [
                        '-c',
                        'user.name=Fixture',
                        '-c',
                        'user.email=fixture@example.invalid',
                        'commit-tree',
                        $body['tree'],
                    ];
                    foreach ($body['parents'] as $parent) {
                        $args[] = '-p';
                        $args[] = $parent;
                    }$args[] = '-m';
                    $args[] = $body['message'];
                    $answer = ['sha' => trim($git($args))];
                    $status = 201;
                } elseif ($method === 'GET' && preg_match(
                    '~/git/commits/([a-f0-9]{40})$~',
                    $path,
                    $m,
                )) {
                    $answer = ['sha' => $m[1],'tree' => ['sha' => trim(
                        $git(['rev-parse',$m[1] . '^{tree}']),
                    )]];
                } elseif ($method === 'GET' && preg_match(
                    '~/commits/([a-f0-9]{40})$~',
                    $path,
                    $m,
                )) {
                    $answer = ['sha' => $m[1],'author' => $state['manual'] ? ['login' => 'human','type' => 'User','id' => 202] : $actor,'committer' => $actor,'commit' => ['message' => $git([
                        'log',
                        '-1',
                        '--format=%B',
                        $m[1],
                    ]),'tree' => ['sha' => trim(
                        $git(['rev-parse',$m[1] . '^{tree}']),
                    )],'verification' => ['verified' => true,'reason' => 'valid']]];
                } elseif ($method === 'GET' && preg_match(
                    '~/git/trees/([a-f0-9]{40})$~',
                    $path,
                    $m,
                )) {
                    $answer = ['sha' => $m[1],'tree' => $entries($m[1]),'truncated' => false];
                } elseif ($method === 'GET' && preg_match(
                    '~/compare/([a-f0-9]{40})\.\.\.([a-f0-9]{40})$~',
                    $path,
                    $m,
                )) {
                    $files = [];
                    foreach (explode(
                        "\n",
                        trim($git(['diff','--name-status',$m[1],$m[2]])),
                    ) as $record) {
                        if ($record === '') {
                            continue;
                        }[$code,$file] = explode(
                            "\t",
                            $record,
                            2,
                        );
                        $files[] = ['filename' => $file,'status' => ['A' => 'added','M' => 'modified','D' => 'removed'][$code]];
                    }
                    $answer = ['merge_base_commit' => ['sha' => trim(
                        $git(['merge-base',$m[1],$m[2]]),
                    )],'status' => $m[1] === $m[2] ? 'identical' : 'ahead','files' => $files];
                } elseif ($method === 'GET' && str_contains($path, '/contents/')) {
                    $file = rawurldecode(explode('/contents/', $path, 2)[1]);
                    $sha = $query['ref'];
                    $record = $git([
                        'ls-tree',
                        $sha,
                        '--',
                        $file,
                    ]);
                    if ($record === '') {
                        $answer = null;
                    } elseif (str_contains($record, ' tree ')) {
                        $list = [];
                        foreach (explode(
                            "\0",
                            rtrim($git(['ls-tree','-r','-z',$sha,'--',$file]), "\0"),
                        ) as $line) {
                            if ($line === '') {
                                continue;
                            }[, $name] = explode(
                                "\t",
                                $line,
                                2,
                            );
                            $list[] = ['path' => $name,'type' => 'file'];
                        }$answer = $list;
                    } else {
                        $answer = ['type' => 'file','encoding' => 'base64','content' => base64_encode(
                            $git(['show',$sha . ':' . $file]),
                        )];
                    }
                } elseif ($method === 'POST' && str_ends_with(
                    $path,
                    '/git/refs',
                )) {
                    $state['head'] = $body['sha'];
                    $answer = ['object' => ['type' => 'commit','sha' => $state['head']]];
                    $status = 201;
                } elseif ($method === 'PATCH' && str_contains(
                    $path,
                    '/git/refs/',
                )) {
                    $state['head'] = $body['sha'];
                    $answer = ['object' => ['type' => 'commit','sha' => $state['head']]];
                } elseif ($method === 'POST' && str_ends_with(
                    $path,
                    '/pulls',
                )) {
                    $state['pr'] = ['number' => 7,'state' => 'open','user' => $actor,'head' => ['ref' => $body['head'],'sha' => $state['head'],'repo' => $repo],'base' => ['ref' => $body['base'],'sha' => $base,'repo' => $repo],'title' => $body['title'],'body' => $body['body'],'html_url' => 'https://github.com/fixture/repo/pull/7'];
                    $answer = $state['pr'];
                    $status = 201;
                } elseif ($method === 'GET' && str_ends_with(
                    $path,
                    '/pulls',
                )) {
                    $answer = $state['pr'] === null ? [] : [
                        $state['pr'],
                    ];
                } elseif ($method === 'GET' && str_ends_with(
                    $path,
                    '/pulls/7',
                )) {
                    $answer = $state['pr'];
                } else {
                    throw new RuntimeException(
                        'Unhandled fixture endpoint: ' . $method . ' ' . $path,
                    );
                }

                return new MockResponse(json_encode(
                    $answer ?? ['message' => 'Not Found',
                    ]), ['http_code' => $answer === null ? 404 : $status]);
            });
            $api = new GitHubClient($http, 'synthetic-token');
            $override = new readonly class ($api)implements \Psr\Container\ContainerInterface {
                public function __construct(
                    private GitHubClientInterface $api,
                ) {} public function has(string $id): bool
                {
                    return$id === GitHubClientInterface::class;
                }public function get(
                    string $id,
                ): mixed {
                    return$this->api;
                }
            };
            $configuration = config(
                ['changelog' => ['working_directory' => $root,'installed_version' => null,'installed_reference' => null,'token' => '','api_url' => 'https://api.github.com','github_output_file' => null]],
            );
            $container = container($override, $configuration, ChangelogServiceProvider::class);
            $options = $container->get(ReleaseOptionsFactoryInterface::class)->create(
                ['workingDirectory' => $root,'repository' => 'fixture/repo','source' => 'tags','generatedFiles' => [
                    'dist/tool',
                ]],
            );
            $service = $container->get(VersionPullRequestServiceInterface::class);
            $result = $service->synchronize($options, new VersionPullRequestInput());
            if ($result->status !== 'created') {
                throw new RuntimeException(
                    'Expected native generated release PR: ' . json_encode(
                        get_object_vars($result),
                    ),
                );
            }
            $head = $state['head'];
            $published = $container->get(
                \FastForward\Changelog\Validator\PublicationEvidenceValidatorInterface::class,
            )->validate(
                $options,
                $head,
            );
            if ($published->version !== '0.1.1' || $published->sha !== $head) {
                throw new RuntimeException(
                    'Native publication evidence rejected exact generated output',
                );
            }
            $writes = $state['writes'];
            $second = $service->synchronize($options, new VersionPullRequestInput());
            if ($second->status !== 'unchanged' || $state['writes'] !== $writes) {
                throw new RuntimeException(
                    'Repeated native release was not idempotent',
                );
            }
            $policy = $container->get(PullRequestPolicyInterface::class);
            if (!$policy->inspectHead($options, $head, 'github-actions[bot]', $base)) {
                throw new RuntimeException(
                    'Native generated scope was not accepted',
                );
            }
            $default = new \FastForward\Changelog\Release\ReleaseOptions(
                $root,
                repository: 'fixture/repo',
                source: 'tags',
            );
            if ($policy->inspectHead($default, $head, 'github-actions[bot]', $base)) {
                throw new RuntimeException(
                    'Default scope accepted generated files',
                );
            }
            $state['manual'] = true;
            if ($policy->inspectHead($options, $head, 'github-actions[bot]', $base)) {
                throw new RuntimeException(
                    'Manual actor accepted',
                );
            }
            $state['manual'] = false;
            $tree = trim($git(['rev-parse',$head . '^{tree}']));
            $env = ['GIT_INDEX_FILE' => $root . '/source-b.index'];
            $git(['read-tree',$tree], environment: $env);
            $source = trim($git(['hash-object','-w','--stdin'], '<?php echo "unreviewed source B";'));
            $git(['update-index','--add','--cacheinfo','100644,' . $source . ',source-b.php'], environment: $env);
            $otherTree = trim($git(['write-tree'], environment: $env));
            $message = $git(['log','-1','--format=%B',$head]);
            $merge = trim(
                $git([
                    '-c',
                    'user.name=Fixture',
                    '-c',
                    'user.email=fixture@example.invalid',
                    'commit-tree',
                    $otherTree,
                    '-p',
                    $head,
                    '-m',
                    $message,
                ]),
            );
            if ($policy->inspectHead($options, $merge, 'github-actions[bot]', $base)) {
                throw new RuntimeException(
                    'Signed unexpected source path accepted',
                );
            }
            try {
                $container->get(MergedPublicationEvidenceValidatorInterface::class)->validateMerged(
                    $options,
                    $merge,
                    $head,
                );

                throw new RuntimeException(
                    'Publisher accepted changed source B with unchanged binary A',
                );
            } catch (InvalidArgumentException $failure) {
                if (!str_contains(
                    $failure->getMessage(),
                    'identical complete Git trees',
                )) {
                    throw$failure;
                }
            }
            $env = ['GIT_INDEX_FILE' => $root . '/tamper.index'];
            $git(['read-tree',$tree], environment: $env);
            $wrong = trim($git(['hash-object','-w','--stdin'], 'different bytes'));
            $git(['update-index','--add','--cacheinfo','100755,' . $wrong . ',dist/tool'], environment: $env);
            $wrongTree = trim($git(['write-tree'], environment: $env));
            $wrongHead = trim(
                $git([
                    '-c',
                    'user.name=Fixture',
                    '-c',
                    'user.email=fixture@example.invalid',
                    'commit-tree',
                    $wrongTree,
                    '-p',
                    $head,
                    '-m',
                    $message,
                ]),
            );
            if ($policy->inspectHead($options, $wrongHead, 'github-actions[bot]', $base)) {
                throw new RuntimeException(
                    'Generated digest mismatch accepted',
                );
            }
            try {
                $container->get(
                    \FastForward\Changelog\Validator\PublicationEvidenceValidatorInterface::class,
                )->validate(
                    $options,
                    $wrongHead,
                );

                throw new RuntimeException(
                    'Publisher accepted generated digest mismatch',
                );
            } catch (RuntimeException $failure) {
                if (str_starts_with(
                    $failure->getMessage(),
                    'Publisher accepted',
                )) {
                    throw$failure;
                }
            }
            $env = ['GIT_INDEX_FILE' => $root . '/mode.index'];
            $git(['read-tree',$tree], environment: $env);
            $blob = trim($git(['rev-parse',$head . ':dist/tool']));
            $git([
                'update-index',
                '--cacheinfo',
                '100644,' . $blob . ',dist/tool',
            ], environment: $env);
            $modeTree = trim($git(['write-tree'], environment: $env));
            $modeHead = trim(
                $git([
                    '-c',
                    'user.name=Fixture',
                    '-c',
                    'user.email=fixture@example.invalid',
                    'commit-tree',
                    $modeTree,
                    '-p',
                    $head,
                    '-m',
                    $message,
                ]),
            );
            if ($policy->inspectHead($options, $modeHead, 'github-actions[bot]', $base)) {
                throw new RuntimeException(
                    'Generated executable mode change accepted',
                );
            }
            self::assertSame('created', $result->status);
            self::assertSame('unchanged', $second->status);
            self::assertSame('0.1.1', $published->version);
            self::assertCount(5, $writes);
            self::assertSame($newBytes, $git(['show', $head . ':dist/tool']));
            self::assertSame(1, (int) trim($git(['rev-list', '--count', $base . '..' . $head])));
        } finally {
            new Filesystem()->remove($root);
        }
    }
}
