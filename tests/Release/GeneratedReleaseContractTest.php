<?php

declare(strict_types=1);

namespace FastForward\Changelog\Tests\Release;

use FastForward\Changelog\Filesystem\PackagePathResolverInterface;
use FastForward\Changelog\Git\GitRepositoryInterface;
use FastForward\Changelog\Release\Factory\ReleaseOptionsFactory;
use FastForward\Changelog\Release\Factory\ReleasePlanFactory;
use FastForward\Changelog\Release\ReceiptCodec;
use FastForward\Changelog\Release\ReleaseOptions;
use FastForward\Changelog\Release\ReleasePlan;
use FastForward\Changelog\Release\ReleaseReceipt;
use InvalidArgumentException;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\TestWith;
use PHPUnit\Framework\TestCase;

#[CoversClass(ReleaseOptionsFactory::class)]
#[CoversClass(ReleasePlanFactory::class)]
#[CoversClass(ReceiptCodec::class)]
#[CoversClass(ReleaseOptions::class)]
#[CoversClass(ReleasePlan::class)]
#[CoversClass(ReleaseReceipt::class)]
final class GeneratedReleaseContractTest extends TestCase
{
    /** Explicit allowlists are canonical, change approval identity, and leave old settings untouched. */
    public function testCanonicalSelectionBindsOptions(): void
    {
        $options = $this->factory()->create(['generatedFiles' => ['dist/z', 'dist/a']]);
        self::assertSame(['dist/a', 'dist/z'], $options->generatedFiles);
        self::assertSame(
            $options->evidenceHash(),
            $this->factory()->create(['generatedFiles' => ['dist/a', 'dist/z']])->evidenceHash(),
        );
        self::assertNotSame($this->factory()->create()->evidenceHash(), $options->evidenceHash());
        self::assertSame([], $this->factory()->create()->generatedFiles);
    }

    /** A generated-file setting cannot escape, overlap managed history, or ambiguously select paths. */
    #[TestWith(['dist/tool'])]
    #[TestWith([['path' => 'dist/tool']])]
    #[TestWith([[false]])]
    #[TestWith([['']])]
    #[TestWith([['/dist/tool']])]
    #[TestWith([['../tool']])]
    #[TestWith([['dist//tool']])]
    #[TestWith([['dist/./tool']])]
    #[TestWith([['dist\\tool']])]
    #[TestWith([["dist/\0tool"]])]
    #[TestWith([['-tool']])]
    #[TestWith([['.git/config']])]
    #[TestWith([['dist/tool', 'dist/tool']])]
    #[TestWith([['CHANGELOG.md']])]
    #[TestWith([['.changelog']])]
    #[TestWith([['.CHANGELOG/a.md']])]
    public function testInvalidSelectionFailsBeforeEffects(mixed $paths): void
    {
        $this->expectException(InvalidArgumentException::class);
        $this->factory()->create(['generatedFiles' => $paths]);
    }

    /** The same four scalar trailers bind both history and actual generated bytes with deterministic replay. */
    public function testReceiptAndOutputBindGeneratedPayload(): void
    {
        $options = $this->factory()->create(['generatedFiles' => ['dist/tool']]);
        $first = $this->plan($options, ['dist/tool' => hash('sha256', 'first')]);
        $second = $this->plan($options, ['dist/tool' => hash('sha256', 'second')]);
        self::assertSame($first->generatedFiles, $first->summary()['generated_files']);
        self::assertNotSame($first->id, $second->id);
        self::assertNotSame($first->commitMessage(), $second->commitMessage());
        self::assertSame($first->id, $this->plan($options, $first->generatedFiles)->id);
        self::assertSame(4, substr_count($first->commitMessage(), 'Changelog-'));
        self::assertStringContainsString(
            'Changelog-Output: ' . ReleasePlan::outputHash('after', $first->generatedFiles),
            $first->commitMessage(),
        );
        self::assertSame(
            ['/fixture/CHANGELOG.md', '/fixture/.changelog/a.md', '/fixture/dist/tool'],
            $first->affectedFiles(),
        );
        self::assertSame(
            $first->generatedFiles,
            (new ReleasePlanFactory(new ReceiptCodec()))->resume(
                $options,
                (new ReceiptCodec())->decode($first->receiptContents),
                '/fixture/CHANGELOG.md',
                'after',
                '/journal',
                $first->receiptContents,
            )->generatedFiles,
        );
        $altered = str_replace(hash('sha256', 'first'), hash('sha256', 'tampered'), $first->receiptContents);
        $this->expectException(InvalidArgumentException::class);
        (new ReceiptCodec())->decode($altered);
    }

    /** Legacy output remains byte-compatible, while map insertion order does not affect generated evidence. */
    public function testOutputIdentityIsCanonicalAndBackwardCompatible(): void
    {
        self::assertSame(hash('sha256', 'history'), ReleasePlan::outputHash('history'));
        $a = ['dist/a' => hash('sha256', 'a'), 'dist/b' => hash('sha256', 'b')];
        self::assertSame(
            ReleasePlan::outputHash('history', $a),
            ReleasePlan::outputHash('history', array_reverse($a, true)),
        );
    }

    /** A plan cannot approve missing, extra or maintenance-only generated outputs. */
    #[TestWith([[], '1.0.1'])]
    #[TestWith([['dist/other' => 'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa'], '1.0.1'])]
    public function testPlanRequiresExactReleaseOutput(array $generated, ?string $next): void
    {
        $this->expectException(InvalidArgumentException::class);
        $this->plan($this->factory()->create(['generatedFiles' => ['dist/tool']]), $generated, $next);
    }

    /** Maintenance binds original base identities without listing generated files as writes. */
    public function testMaintenanceRetainsGeneratedEvidenceWithoutWritingIt(): void
    {
        $options = $this->factory()->create(['generatedFiles' => ['dist/tool']]);
        $plan = $this->plan($options, ['dist/tool' => hash('sha256', 'base bytes')], null);
        self::assertSame('maintenance', $plan->mode());
        self::assertNotContains('/fixture/dist/tool', $plan->affectedFiles());
        self::assertSame($plan->generatedFiles, $plan->summary()['generated_files']);
    }

    /** Equal member names in distinct JSON objects are valid, including escaped punctuation in values. */
    public function testGeneratedRootPathMayShareAReceiptFieldName(): void
    {
        $options = $this->factory()->create(['generatedFiles' => ['notes']]);
        $plan = $this->plan($options, ['notes' => hash('sha256', '{"notes": "value"}')]);
        $codec = new ReceiptCodec();
        $evidence = $codec->decode($plan->receiptContents)->data;
        self::assertSame($plan->generatedFiles, $evidence['generated_files']);
        $duplicate = str_replace(
            '"notes": "' . hash('sha256', '{"notes": "value"}') . '"',
            '"notes": "' . hash('sha256', 'one') . '", "notes": "' . hash('sha256', 'two') . '"',
            $plan->receiptContents,
        );
        $this->expectExceptionMessage('Duplicate release receipt key: notes');
        $codec->decode($duplicate);
    }
    /** Invalid generated receipt maps are rejected before their identity is accepted. */
    #[TestWith([[]])]
    #[TestWith([['dist/tool' => 'bad']])]
    #[TestWith([['../tool' => 'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa']])]
    #[TestWith([['CHANGELOG.md' => 'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa']])]
    #[TestWith([['.changelog/a.md' => 'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa']])]
    public function testReceiptRejectsInvalidGeneratedMap(array $generated): void
    {
        $codec = new ReceiptCodec();
        $evidence = $codec->decode($this->plan(new ReleaseOptions('/fixture'), [])->receiptContents)->data;
        unset($evidence['id']);
        $evidence['generated_files'] = $generated;
        $this->expectException(InvalidArgumentException::class);
        $codec->encode($evidence);
    }

    /** Supplies deterministic options with filesystem and Git observations replaced. */
    private function factory(): ReleaseOptionsFactory
    {
        $paths = $this->createStub(PackagePathResolverInterface::class);
        $paths->method('absolutePath')->willReturn('/fixture');
        $paths->method('isAbsolute')->willReturnCallback(static fn(string $path): bool => str_starts_with($path, '/'));

        return new ReleaseOptionsFactory($paths, $this->createStub(GitRepositoryInterface::class));
    }

    /** Creates native evidence values without accessing files, time, processes or network. */
    private function plan(ReleaseOptions $options, array $generated, ?string $next = '1.0.1'): ReleasePlan
    {
        return (new ReleasePlanFactory(new ReceiptCodec()))->create(
            $options,
            str_repeat('a', 40),
            '1.0.0',
            $next,
            null === $next ? null : 'patch',
            null === $next ? [] : ['/fixture/.changelog/a.md' => hash('sha256', 'note')],
            [],
            '/fixture/CHANGELOG.md',
            'before',
            'after',
            'notes',
            '/journal',
            null,
            generatedFiles: $generated,
        );
    }
}
